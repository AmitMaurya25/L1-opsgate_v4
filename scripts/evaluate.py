"""Run the labeled synthetic eval set and write docs/EVAL_REPORT.md + docs/SAFETY_TESTS.md with ACTUAL observed results.
Usage: python -m scripts.evaluate   (token numbers are chars/4 ESTIMATES in DEMO_MODE; synthetic data, authored by the team)."""
import json, statistics, sys, tempfile, time
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent; sys.path.insert(0, str(ROOT))
import config as C, llm
from engine import Engine
from kb import get_kb

def actual(m):
    return 'blocked' if m['route'] == 'blocked' else 'abstain' if m.get('outcome') == 'abstained' else m['route']

def run(rel=None):
    if rel is not None: C.REL_MIN = rel
    qs = json.loads((ROOT / 'data' / 'eval_queries.json').read_text()); tmp = Path(tempfile.mkdtemp()); rows = []; kb = get_kb()
    for i, q in enumerate(qs):
        e = Engine(tmp / f'{i}.db'); s, t = e.act('e', {'kind': 'new'})
        for p in q.get('prior', []): e.act('e', {'kind': 'chat', 'thread': t, 'text': p})
        t0 = time.perf_counter(); s, _ = e.act('e', {'kind': 'chat', 'thread': t, 'text': q['query']}); dt = time.perf_counter() - t0
        m = s['threads'][0]['messages'][-1]; a = actual(m)
        rec = bool(set(h['chunk_id'] for h in kb.search(q['query'], 5)) & set(q['expected_kb'])) if q['expected_kb'] else None
        grounded = (bool(m.get('cites')) and set(m['cites']) <= kb.ids) if a == 'rag' else None
        rows.append(dict(q=q, actual=a, ok=a == q['expected'], recall=rec, grounded=grounded, ms=dt * 1000, est_in=m.get('est_in')))
    return rows

def pct(x): return f'{100 * sum(x) / len(x):.0f}% ({sum(x)}/{len(x)})' if x else 'n/a'

def main():
    base = C.REL_MIN; sweep = []
    for r in (.15, .25, .35, .45, .55, .65):
        rr = [x for x in run(r) if x['q']['split'] == 'calib']; sweep.append((r, sum(x['ok'] for x in rr), len(rr)))
    rows = run(base); cal = [r for r in rows if r['q']['split'] == 'calib']; tst = [r for r in rows if r['q']['split'] == 'test']
    kb_text = ' '.join(c['text'] for c in get_kb().chunks); naive = llm.est(llm.SYSTEM) + llm.est(kb_text)
    eng = [r['est_in'] for r in rows if r['est_in']]; red = 100 * (1 - statistics.mean(eng) / naive)
    lat = sorted(r['ms'] for r in rows); fails = [r for r in rows if not r['ok'] or r['recall'] is False]
    L = ['# OpsGate evaluation report (auto-generated by `python -m scripts.evaluate`)', '',
         f'Mode: DEMO_MODE={C.DEMO_MODE} (deterministic extractive answers, no model call). REL_MIN={base}. KB chunks: {len(get_kb().chunks)}. Queries: {len(rows)} ({len(cal)} calibration, {len(tst)} held-out test).',
         '**Caveat:** synthetic KB and queries were authored by the same team; numbers are optimistic and are NOT benchmark claims. Re-run on organizer-supplied/real tickets before quoting.', '',
         '| Metric | Calibration | Held-out test | Target (plan) |', '|---|---|---|---|',
         f"| Routing/outcome accuracy | {pct([r['ok'] for r in cal])} | {pct([r['ok'] for r in tst])} | >=95% |",
         f"| Recall@5 (retrieval, labeled queries) | {pct([r['recall'] for r in cal if r['recall'] is not None])} | {pct([r['recall'] for r in tst if r['recall'] is not None])} | >=90% |",
         f"| Grounded answers (valid citations) | {pct([r['grounded'] for r in cal if r['grounded'] is not None])} | {pct([r['grounded'] for r in tst if r['grounded'] is not None])} | >=95% |",
         f"| Abstain/block correctness | {pct([r['ok'] for r in cal if r['q']['expected'] in ('abstain', 'blocked')])} | {pct([r['ok'] for r in tst if r['q']['expected'] in ('abstain', 'blocked')])} | 100% blocked |", '',
         f'Latency (local, DEMO_MODE): p50 {statistics.median(lat):.1f} ms, p95 {lat[int(.95 * len(lat)) - 1]:.1f} ms. Live-model latency not measured.', '',
         f'Context size (ESTIMATE, chars/4, not provider-measured): naive baseline (system + whole KB) ~{naive} tokens vs engineered prompt (evidence only) mean ~{statistics.mean(eng):.0f} tokens = ~{red:.0f}% reduction. Quality parity with a naive baseline was NOT measured.', '',
         '## REL_MIN calibration sweep (calibration split, outcome accuracy)', 'Accuracy is flat across 0.15-0.55, so the gate is not sharply calibrated on this small set; 0.35 was chosen mid-plateau. Recalibrate on real queries.', '', '| REL_MIN | correct |', '|---|---|'] + [f'| {r} | {a}/{n} |' for r, a, n in sweep]
    L += ['', '## Failures / misses', ''] + ([f"- [{r['q']['split']}] '{r['q']['query']}': expected {r['q']['expected']}, got {r['actual']}, recall={r['recall']}" for r in fails] or ['- none on this set (small, self-authored set; expect real-world misses)'])
    (ROOT / 'docs' / 'EVAL_REPORT.md').write_text('\n'.join(L) + '\n')
    from tests.safety_cases import CASES
    S = ['# Safety test results (auto-generated; the ten tests from the API Usage Guide)', '', '| # | Test | Scenario | Expected | Observed | Result |', '|---|---|---|---|---|---|']
    for n, name, sc, exp, fn in CASES:
        obs, ok = fn(Path(tempfile.mkdtemp())); S.append(f'| {n} | {name} | {sc} | {exp} | {obs} | {"PASS" if ok else "FAIL"} |')
    S += ['', 'Not applicable / limits: file-upload and attachment-injection tests are N/A (no upload feature in this build). Authentication is a demo session identity (random per browser session), not enterprise SSO.']
    (ROOT / 'docs' / 'SAFETY_TESTS.md').write_text('\n'.join(S) + '\n')
    print('\n'.join(L[:12])); print('safety:', sum(1 for l in S if l.endswith('PASS |')), '/ 10 pass')

if __name__ == '__main__': main()
